"""The events collector: agents post hook events, the operator reads them.

Two credentials, split by direction (`docs/decisions.md` ADR 72):

- **Reading** (`GET /events`) takes the one read token, `COLLECTOR_READ_TOKEN`,
  which only the operator on the host holds. No agent service is given it, so
  code running inside an agent container cannot read what another agent did.
- **Writing** (`POST /events`) takes a write token, one per agent, each bound to
  that agent's `source_app` by `COLLECTOR_WRITE_TOKENS`. The collector stores
  the `source_app` the token is bound to and ignores whatever the body says, so
  a leaked write token can forge events only as the agent it already belonged
  to.

There is no open mode. A collector started without a read token, or without
any write token, exits naming the missing variable rather than answering
everyone: a `.env` written before ADR 72 is a collector that does not start,
not a collector that serves the whole network.
"""
from __future__ import annotations

import logging
import os
import sys

from flask import Flask, jsonify, request

from observability.auth import _bearer, check_token
from observability.collector import db

#: The variable holding the operator's read token. Named in the startup
#: refusal, so it is a constant rather than a string spelt twice.
READ_TOKEN_VAR = "COLLECTOR_READ_TOKEN"

#: The variable holding the write-token map: comma-separated
#: `<source_app>=<token>` entries, assembled in the compose file next to each
#: agent's `SOURCE_APP` so the binding is written where it can be read.
WRITE_TOKENS_VAR = "COLLECTOR_WRITE_TOKENS"


#: Where the collector listens; unchanged since the development server.
HOST = "0.0.0.0"
PORT = 8787

#: Request threads (`docs/decisions.md` ADR 417): each request is one SQLite
#: insert or one bounded select, and waitress queues the rest.
THREADS = 4


class ConfigError(Exception):
    """The collector's credentials are missing or do not make sense.

    Raised by `parse_write_tokens` and `load_config` with a message that names
    the variable, and turned into a non-zero exit by `__main__`. An exception
    rather than a `sys.exit` inside the parser so the tests can check each
    refusal by its message without catching `SystemExit`.
    """


def parse_write_tokens(raw: str | None) -> dict[str, str]:
    """`COLLECTOR_WRITE_TOKENS` as a `{source_app: token}` mapping.

    Each entry is split on its *first* `=`: a source_app never holds one, and a
    token generated by `scripts/configure.sh` is hex, but splitting on the first
    keeps a token that does carry an `=` whole rather than truncated. Entries
    and both halves are whitespace-stripped so a map wrapped across lines in a
    compose file still parses.

    Every refusal is about one thing that would otherwise become a silent hole:
    an empty token is an agent whose `.env` key was never generated (compose
    substitutes nothing for it), and two agents sharing a token would let one
    post as the other — the binding this map exists to make would be a lookup
    that picks whichever comes first.
    """
    if not raw or not raw.strip():
        raise ConfigError(f"{WRITE_TOKENS_VAR} is not set: the collector accepts no event without it")
    tokens: dict[str, str] = {}
    for entry in raw.split(","):
        entry = entry.strip()
        if not entry:
            continue
        source_app, sep, token = entry.partition("=")
        source_app, token = source_app.strip(), token.strip()
        if not sep or not source_app:
            raise ConfigError(
                f"{WRITE_TOKENS_VAR} has an entry that is not <source_app>=<token>"
            )
        if not token:
            raise ConfigError(f"{WRITE_TOKENS_VAR} has an empty token for {source_app}")
        if source_app in tokens:
            raise ConfigError(f"{WRITE_TOKENS_VAR} names {source_app} twice")
        if token in tokens.values():
            raise ConfigError(f"{WRITE_TOKENS_VAR} gives {source_app} a token another agent already has")
        tokens[source_app] = token
    if not tokens:
        raise ConfigError(f"{WRITE_TOKENS_VAR} is not set: the collector accepts no event without it")
    return tokens


def load_config(environ) -> tuple[str, dict[str, str]]:
    """The read token and the write-token map out of `environ`, or `ConfigError`.

    The read token is checked first so an operator whose `.env` predates ADR 72
    — missing both — is told about the one that guards the reads. A write token
    equal to the read token is refused: an agent holding it could read every
    event, which is the one thing the split is for.
    """
    read_token = (environ.get(READ_TOKEN_VAR) or "").strip()
    if not read_token:
        raise ConfigError(f"{READ_TOKEN_VAR} is not set: the collector serves no read without it")
    write_tokens = parse_write_tokens(environ.get(WRITE_TOKENS_VAR))
    for source_app, token in write_tokens.items():
        if token == read_token:
            raise ConfigError(
                f"{WRITE_TOKENS_VAR} gives {source_app} the same token as {READ_TOKEN_VAR}"
            )
    return read_token, write_tokens


def _source_app_for(presented: str | None, write_tokens: dict[str, str]) -> str | None:
    """The source_app bound to this write token, or None.

    Every entry is compared, and with `check_token`, so the time a refusal takes
    does not depend on which agent's token a guess came closest to. Agents are
    a handful, so the full scan costs nothing.
    """
    match = None
    for source_app, token in write_tokens.items():
        if check_token(presented, token):
            match = source_app
    return match


def _unauthorized():
    return (
        jsonify({"error": "a valid bearer token is required"}),
        401,
        {"WWW-Authenticate": 'Bearer realm="ia-harness-collector"'},
    )


def create_app(db_path: str, read_token: str, write_tokens: dict[str, str]) -> Flask:
    """The collector, guarded by `read_token` and `write_tokens`.

    Both are required arguments with no default, for the reason the module
    docstring gives: a caller that forgets one gets a `TypeError`, not an open
    collector. `check_token` already refuses an empty token, so an empty
    argument here closes the route rather than opening it.
    """
    db.init_db(db_path)
    app = Flask(__name__)

    @app.post("/events")
    def post_event():
        # Authenticated before the body is parsed: a caller without a token
        # learns nothing about what a valid event looks like.
        source_app = _source_app_for(
            _bearer(request.headers.get("Authorization", "")), write_tokens
        )
        if source_app is None:
            return _unauthorized()
        body = request.get_json(force=True)
        # `source_app` comes from the token. A `source_app` in the body is
        # ignored rather than refused when it disagrees: the hook still sends
        # it, and a mismatch is either a misconfigured agent, whose events are
        # still worth having under the name the operator gave it, or a forgery,
        # which this binding already defeats.
        event_type = body.get("event_type")
        payload = body.get("payload", {})
        if not event_type:
            return jsonify({"error": "event_type is required"}), 400
        db.insert_event(db_path, source_app, event_type, payload)
        return jsonify({"status": "ok"}), 201

    @app.get("/events")
    def get_events():
        # The read token only. A write token is refused here even though it
        # is valid on POST: an agent's token is readable by the repo code that
        # runs in that agent's container.
        if not check_token(_bearer(request.headers.get("Authorization", "")), read_token):
            return _unauthorized()
        limit = int(request.args.get("limit", 100))
        source_app = request.args.get("source_app")
        return jsonify(db.list_events(db_path, limit=limit, source_app=source_app))

    return app


def main(environ=None) -> Flask:
    """The app built from the environment, or exit 2 naming what is missing."""
    environ = os.environ if environ is None else environ
    try:
        read_token, write_tokens = load_config(environ)
    except ConfigError as e:
        print(f"collector: refusing to start: {e}", file=sys.stderr)
        raise SystemExit(2) from None
    return create_app(
        environ.get("COLLECTOR_DB_PATH", "/data/events.db"), read_token, write_tokens
    )


def _log_waitress() -> None:
    """Send waitress's start line and queue warnings to stderr (ADR 420)."""
    logger = logging.getLogger("waitress")
    logger.setLevel(logging.INFO)
    if not logger.handlers:
        handler = logging.StreamHandler()
        handler.setFormatter(logging.Formatter(logging.BASIC_FORMAT))
        logger.addHandler(handler)


def run(environ=None) -> None:
    """Serve the collector from waitress (`docs/decisions.md` ADR 417)."""
    app = main(environ)
    # Imported after `main`: a refused configuration exits 2 whether or not
    # waitress is installed.
    from waitress import serve

    _log_waitress()
    serve(app, host=HOST, port=PORT, threads=THREADS)


if __name__ == "__main__":
    run()
